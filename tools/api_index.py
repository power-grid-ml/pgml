"""Write or check the public API index of a package.

The index lists every name exported through ``__all__`` by the package and its public
(non-underscore) modules, with its signature and the first line of its docstring. It is
generated from the installed code, so it cannot drift: ``--check`` exits non-zero when the
committed file differs from what the code produces.

Usage (from the repository root)::

    python tools/api_index.py <package> [--output API_INDEX.md] [--check]
"""

from __future__ import annotations

import argparse
import importlib
import inspect
import pkgutil
import re
import sys
from pathlib import Path

HEADER = (
    "# Public API of `{package}`\n\n"
    "Generated by `tools/api_index.py` from each module's `__all__`; do not edit by hand.\n"
    "Full documentation: the docstrings (published as the API reference).\n"
)


def _public_modules(package: str) -> list[str]:
    root = importlib.import_module(package)
    names = [package]
    for info in pkgutil.walk_packages(root.__path__, prefix=f"{package}."):
        if any(part.startswith("_") for part in info.name.split(".")):
            continue
        names.append(info.name)
    return sorted(names)


def _first_line(obj: object) -> str:
    doc = inspect.getdoc(obj) or ""
    return doc.strip().splitlines()[0] if doc.strip() else ""


_QUALIFIED = re.compile(r"\b(?:[A-Za-z_][A-Za-z0-9_]*\.)+(?=[A-Za-z_])")
_MAX_DEFAULT = 24


def _signature(obj: object) -> str:
    """Compact signature: class parameters by name, function annotations unqualified."""
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return ""
    if inspect.isclass(obj):
        return "(" + ", ".join(
            p.name if p.default is p.empty else f"{p.name}=…"
            for p in sig.parameters.values()
            if p.kind not in (p.VAR_POSITIONAL, p.VAR_KEYWORD)
        ) + ")"
    parts = []
    for p in sig.parameters.values():
        params = p.replace(annotation=p.empty, default=p.empty)
        text = str(params)
        if p.annotation is not p.empty:
            ann = p.annotation if isinstance(p.annotation, str) else inspect.formatannotation(p.annotation)
            text += ": " + _QUALIFIED.sub("", ann)
        if p.default is not p.empty:
            default = repr(p.default)
            text += " = " + (default if len(default) <= _MAX_DEFAULT else "…")
        parts.append(text)
    text = "(" + ", ".join(parts) + ")"
    if sig.return_annotation is not sig.empty:
        ret = sig.return_annotation
        ret = ret if isinstance(ret, str) else inspect.formatannotation(ret)
        text += " -> " + _QUALIFIED.sub("", ret)
    return text


def _describe(name: str, obj: object) -> str:
    if inspect.isclass(obj):
        kind = "class"
    elif callable(obj):
        kind = "def"
    else:
        return f"- `{name}` — {type(obj).__name__}"
    summary = _first_line(obj)
    line = f"- {kind} `{name}{_signature(obj)}`"
    return f"{line} — {summary}" if summary else line


def build_index(package: str) -> str:
    sections = [HEADER.format(package=package)]
    seen: dict[int, str] = {}
    for module_name in _public_modules(package):
        module = importlib.import_module(module_name)
        exported = getattr(module, "__all__", None)
        if not exported:
            continue
        lines = []
        for name in sorted(exported):
            obj = getattr(module, name)
            owner = seen.get(id(obj))
            if owner is not None and not isinstance(obj, (int, float, str, bool)):
                lines.append(f"- `{name}` — re-exported from `{owner}`")
                continue
            seen.setdefault(id(obj), module_name)
            lines.append(_describe(name, obj))
        sections.append(f"\n## `{module_name}`\n\n" + "\n".join(lines) + "\n")
    return "".join(sections)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("package")
    parser.add_argument("--output", type=Path, default=Path("API_INDEX.md"))
    parser.add_argument("--check", action="store_true", help="fail when the file is stale")
    args = parser.parse_args(argv)

    text = build_index(args.package)
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != text:
            print(f"{args.output} is out of date; run tools/api_index.py {args.package}", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
